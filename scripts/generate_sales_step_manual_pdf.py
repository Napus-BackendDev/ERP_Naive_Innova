def steps(rows, prefix):
    data = [[p("ข้อ", "TH_Small2"), p("ให้ทำ", "TH_Small2"), p("แล้วจะเกิดอะไรขึ้น", "TH_Small2"), p("ตรวจสอบก่อนทำต่อ", "TH_Small2")]]
